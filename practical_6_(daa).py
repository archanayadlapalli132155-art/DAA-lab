# Chain Matrix Multiplication using Dynamic Programming

def matrix_chain_order(p):
    n = len(p) - 1

    # m[i][j] stores minimum multiplication cost
    m = [[0 for _ in range(n + 1)] for _ in range(n + 1)]

    # s[i][j] stores the position at which the chain is split
    s = [[0 for _ in range(n + 1)] for _ in range(n + 1)]

    # Chain length
    for length in range(2, n + 1):

        for i in range(1, n - length + 2):
            j = i + length - 1

            m[i][j] = float('inf')

            # Try every possible split
            for k in range(i, j):
                cost = (
                    m[i][k]
                    + m[k + 1][j]
                    + p[i - 1] * p[k] * p[j]
                )

                if cost < m[i][j]:
                    m[i][j] = cost
                    s[i][j] = k

    return m, s


# Function to print optimal parenthesization
def print_optimal_parenthesization(s, i, j):

    if i == j:
        return f"A{i}"

    k = s[i][j]

    left = print_optimal_parenthesization(s, i, k)
    right = print_optimal_parenthesization(s, k + 1, j)

    return f"({left} × {right})"


