# Matrix dimensions
# A1 = 10x20
# A2 = 20x30
# A3 = 30x40
# A4 = 40x30

p = [10, 20, 30, 40, 30]

# Calculate minimum cost
m, s = matrix_chain_order(p)

n = len(p) - 1

# Display matrices
print("Matrix Dimensions:")
for i in range(1, n + 1):
    print(f"A{i} = {p[i-1]} x {p[i]}")

# Display minimum cost
print("\nMinimum number of scalar multiplications:")
print(m[1][n])

# Display optimal parenthesization
print("\nOptimal Parenthesization:")
print(print_optimal_parenthesization(s, 1, n))

# Display DP table
print("\nDynamic Programming Cost Table:")

for i in range(1, n + 1):
    for j in range(1, n + 1):
        if i <= j:
            print(f"m[{i}][{j}] = {m[i][j]}")
